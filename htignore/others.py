import pathlib, hashlib, base64, re, requests, json, shutil
from htmlparser import html_to_jsonml, process_htdata
from custom_format import parse_named_blocks
from glob import glob

image_formats = {'.png', '.jpeg', '.jpg', '.webp', '.avif'}
truncated_len = 8


def makeready2():
    data = dict()
    folder = 'imgdata'
    alt_texts = dict()
    with open('misc-ai/.altText.txt', 'rt', encoding='utf8') as file:
        alt_texts = parse_named_blocks(file.read())
    for path in pathlib.Path('misc-ai').iterdir():
        if path.suffix not in image_formats:
            continue
        with open(path, 'rb') as file:
            content = file.read()
            hashed = base64.b64encode(hashlib.sha512(content).digest()).decode('utf-8') \
                .replace('/', '_').replace('+', '-').replace('=', str())[0::truncated_len]
        with open(f'../{folder}/{hashed}{path.suffix}', 'wb') as file:
            file.write(content)
        resp = requests.get(f'http://localhost/gallery/dev-only/imgdata.php?hash={hashed}{path.suffix}')
        sizes = resp.headers.get('image-size')
        if sizes is None:
            continue
        matched = re.search('w=(\\d+), h=(\\d+)', sizes)
        data[f'{hashed}{path.suffix}'] = {
            'w': int(matched.group(1)), 'h': int(matched.group(2)),
            't': resp.headers['image-type'], 'oname': path.name}
        data[f'{hashed}{path.suffix}']['alt'] = alt_texts.get(path.name, path.name)
    # Sort data's entries by the order of keys in alt_texts using each entry's oname
    sorted_data = dict()
    for alt_key in alt_texts.keys():
        for k, v in data.items():
            if v.get('oname') == alt_key:
                sorted_data[k] = v
                break
    # Include any remaining entries that weren't in alt_texts
    for k, v in data.items():
        if k not in sorted_data:
            sorted_data[k] = v
    data = sorted_data
    with open(f'../{folder}/.misc-ai.json', 'wt', encoding='utf8') as file:
        file.write(json.dumps(data))
    return {'errored': False}


def mkstory(character_data, reverse_map, unidata):
    shutil.rmtree('../' + (folder := 'storydata'))
    pathlib.Path('../' + folder).mkdir(exist_ok=True, parents=True)
    with open(f'../{folder}/.htaccess', 'wt', encoding='utf8') as file:
        file.write('# autogenerated, do not edit\n')
        file.write('RewriteEngine on\n')
        file.write('RewriteBase /gallery/imgdata/\n')
        file.write('RewriteCond %{HTTP:Sec-Fetch-Site} ^cross-site$ [NC]\n')
        file.write('RewriteRule ^ - [F,L]\n')
        file.write('Header append vary sec-fetch-site\n')
        # file.write('Header set Cache-Control "public, max-age=600"\n\n')
    for globed in glob('universe-images/*/*/stories/*.html'):
        title = 'Unknown Story'
        with open(globed, 'rb') as src:
            jsonml = process_htdata(html_to_jsonml(b'<body>' + src.read()), reverse_map)
            try:
                if jsonml[2][0] == 'script':
                    if jsonml[2][1]['type'] == 'text/prs.storydata+json':
                        data = json.loads(jsonml[2][2])
                        title = data['title']
                        del jsonml[2]
                jsonml[0] = 'main'
                jsonml[1]['class'] = 'character-profile'
                jsonml.insert(2, ['h1', dict(), title])
            except (KeyError, IndexError, TypeError) as err:
                print(err)
                continue
        uni = pathlib.Path(globed).parent.parent.parent.name
        charid = pathlib.Path(globed).parent.parent.name
        resp = requests.post(
            f'http://localhost/gallery/dev-only/storytime.php',
            json={'character_data': character_data, 'jsonml': jsonml}, headers={
                'data-char-title': character_data[uni][charid]['main.json']['name'],
                'data-uni-name': unidata[uni]['humanName'], 'data-univ': uni,
                'data-charid': charid, 'data-title': title, 'data-file-name': pathlib.Path(globed).stem,
                'data-bg': character_data[uni][charid]['main.json'].get('secondaryColor', 'null'),
                'data-bo': character_data[uni][charid]['main.json'].get('primaryColor', 'null'),
            })
        if resp.ok:
            with open(pathlib.Path('../storydata') / f'{uni}-{charid}--{pathlib.Path(globed).name}', 'wb') as out:
                out.write(resp.content)
    return False


